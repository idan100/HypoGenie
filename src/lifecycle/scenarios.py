"""
Lifecycle Validation Runner.

Orchestrates the full resource lifecycle experiment:

  1. Start backend sidecar on the host (HTTP/1.1 with chunked streaming, sidecar_port)
  2. Start a Caddy container configured to reverse_proxy to the sidecar
       - --add-host=host.docker.internal:host-gateway
       - admin 0.0.0.0:2019 (so pprof is reachable via port-mapped 2020)
  3. For each of batch_count rounds:
       a. Read baseline goroutine count from Caddy pprof
       b. For each cancel scenario (C + D): run ops_per_batch QUIC H3 ops
          using an event-driven client that waits for the backend "STARTED"
          chunk before sending RESET_STREAM.
       c. Read sidecar /metrics → RetentionSample
  4. Run matched control arm (Scenario A — all ops complete normally)
  5. Post-attack recovery observation: poll /metrics every 1s for
     recovery_wait_s and record outstanding_cleanups time-series.
  6. Call analysis.analyze() → outcome + notes
  7. Teardown container and sidecar

Scenario ids and cancel semantics (from plan.cancel_timing):
  A — complete (no cancel)                           → control arm
  B — early cancel (before backend dispatch)
  C — cancel on start signal (backend just started)  → main attack arm
  D — cancel 300ms after start signal                → main attack arm
"""

